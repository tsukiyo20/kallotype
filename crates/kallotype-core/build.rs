fn emit_matrix(code: &mut String, name: &str, rows: &[Vec<f64>]) {
    writeln!(code, "#[allow(clippy::approx_constant)]").unwrap();
    writeln!(code, "const {name}: [[f64; GRID_LEN]; 3] = [").unwrap();
    for row in rows {
        emit_row(code, "", row);
    }
    writeln!(code, "];\n").unwrap();
}

fn emit_row(code: &mut String, name: &str, row: &[f64]) {
    if name.is_empty() {
        code.push_str("    [");
    } else {
        writeln!(code, "#[allow(clippy::approx_constant)]").unwrap();
        write!(code, "const {name}: [f64; GRID_LEN] = [").unwrap();
    }
    for (index, value) in row.iter().enumerate() {
        if index > 0 {
            code.push_str(", ");
        }
        write!(code, "{value:.5}").unwrap();
    }
    if name.is_empty() {
        code.push_str("],\n");
    } else {
        code.push_str("];\n\n");
    }
}
