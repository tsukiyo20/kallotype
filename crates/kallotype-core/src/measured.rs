/// No mask, for the films that have none.
///
/// A reversal does not need one: what it transmits is the picture, and its
/// curve already carries the density of an unexposed slide. The field is not
/// optional because a negative's mask is real, so the honest value for "there
/// is nothing here" is a table of zeros rather than a borrowed film's mask.
pub(crate) const NO_MASK: [f64; GRID_LEN] = [0.0; GRID_LEN];

/// No dyes, for the films that have none.
///
/// A silver image is neutral and its density is carried by the grain, not by a
/// coupler, so there are no dye curves to give. The model's dye tables are
/// absorption, and zero absorption is the honest statement of that.
pub(crate) const NO_DYES: [[f64; GRID_LEN]; 3] = [[0.0; GRID_LEN]; 3];

#[cfg(test)]
mod tests {
    use super::*;

    /// The film's dye curves were published peak-normalised, so three peaks at
    /// 1.0 is the transcription check the data sheet gives us for free.
    #[test]
    fn the_dye_peaks_land_where_the_data_sheet_says() {
        for (name, table) in ["cyan", "magenta", "yellow"].iter().zip(&FILM_DYES) {
            let peak = table.iter().copied().fold(f64::NEG_INFINITY, f64::max);
            assert!((peak - 1.0).abs() < 0.01, "{name} peaks at {peak}");
        }
    }

    /// The tables have to be on the model's grid, or every dot product silently
    /// disagrees about wavelength.
    #[test]
    fn the_tables_are_on_the_models_grid() {
        let one = spectrum(&FILM_MASK);
        let two = spectrum(&PAPER_DYES[0]);
        assert!(one.shares_grid(&two));
        assert_eq!(one.len(), GRID_LEN);
    }

    /// The model carries the film's minimum density twice — as this spectrum for
    /// the print, and as three status densities on the stock for the scalar path
    /// — because those are the two shapes the two paths need. This is the test
    /// that they are the same quantity.
    ///
    /// Sampled at the status filter peaks, which is the approximation the
    /// model's status-to-analytical unmixing already makes. Green is the loosest
    /// of the three for that reason: 550 nm is the middle of a broad band, not a
    /// wavelength anything is measured at.
    #[test]
    fn the_mask_is_the_measured_minimum_density() {
        // Plateaus of the data sheet's sensitometric curves at -8 stops.
        const MEASURED: [f64; 3] = [0.1867, 0.5782, 0.8319];
        let mask = spectrum(&FILM_MASK);
        for (wavelength, expected) in [650.0, 550.0, 450.0].iter().zip(MEASURED) {
            let at = mask.interpolate(*wavelength);
            assert!(
                (at - expected).abs() < 0.06,
                "{wavelength} nm: mask {at:.4} against measured {expected:.4}"
            );
        }
    }

    /// The mask absorbs blue and passes red: that is the whole reason it exists.
    #[test]
    fn the_mask_is_orange() {
        let at = |wavelength: f64| {
            FILM_MASK[((wavelength - GRID_START_NM) / GRID_STEP_NM).round() as usize]
        };
        assert!(
            at(450.0) > at(650.0),
            "blue {} vs red {}",
            at(450.0),
            at(650.0)
        );
    }
}
